// Function to get country flag by code (returns emoji string)
export const getCountryFlag = (countryCode) => {
  return countryFlags[countryCode] || "🏳️";
};

// Function to get country flag emoji string for HTML rendering
export const getCountryFlagEmoji = (countryCode) => {
  return countryFlags[countryCode] || "🏳️";
};

// Function to generate Twemoji-compatible HTML for country flags
export const getCountryFlagHTML = (countryCode, style = "") => {
  const flagEmoji = getCountryFlagEmoji(countryCode);
  return `<div style="font-size:24px; filter: drop-shadow(0 2px 4px rgba(0,0,0,0.2)); transform: translate(-50%, -50%); position: absolute; left: 50%; top: 50%; ${style}">${flagEmoji}</div>`;
};
